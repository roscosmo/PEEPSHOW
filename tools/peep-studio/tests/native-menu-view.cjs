const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),readline=require('node:readline');
const {spawn}=require('node:child_process');
const {app,BrowserWindow,ipcMain}=require('electron');
const root=path.resolve(__dirname,'../../..');
const source=path.join(root,'examples/authoring/native_v2_menu.peepproj');
const output=path.resolve('dist/native-menu-view');fs.mkdirSync(output,{recursive:true});
app.setPath('userData',path.join(output,'profile'));app.disableHardwareAcceleration();
let child,id=0;const pending=new Map(),errors=[],operations=[];
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const watchdog=setTimeout(()=>{child?.kill();app.exit(1)},30000);
app.whenReady().then(async()=>{
  child=spawn(process.env.PEEPSHOW_PYTHON,['-u','tools/authoring/egg_tool.py','service'],{cwd:root,windowsHide:true});
  readline.createInterface({input:child.stdout}).on('line',line=>{
    const r=JSON.parse(line),p=pending.get(r.id);pending.delete(r.id);
    if(r.ok)p.resolve(r.result);else {errors.push(r.error);p.reject(new Error(JSON.stringify(r.error)))}
  });
  child.stderr.on('data',data=>process.stderr.write(data));
  ipcMain.handle('export:source',()=>source);
  ipcMain.handle('export:service',(_,operation,params)=>{
    assert(!['project.save','project.create','project.build_package'].includes(operation));
    if(operation==='project.apply_commands') assert(params.commands.every(command=>command.kind==='object_override.set'));
    operations.push(operation);
    return new Promise((resolve,reject)=>{const requestId=String(++id);pending.set(requestId,{resolve,reject});
      child.stdin.write(JSON.stringify({protocol_version:1,id:requestId,operation,params})+'\n')});
  });
  const window=new BrowserWindow({width:1440,height:1000,show:false,webPreferences:{
    preload:path.join(__dirname,'restricted-export-preload.cjs'),sandbox:true,contextIsolation:true,offscreen:true}});
  const evaluate=code=>window.webContents.executeJavaScript(code);
  const button=async name=>{await evaluate(`([...document.querySelectorAll('button')].find(e=>e.textContent.trim()===${JSON.stringify(name)})).click()`);await wait(700)};
  const capture=async name=>{window.webContents.invalidate();await wait(150);fs.writeFileSync(path.join(output,name),(await window.webContents.capturePage()).toPNG())};
  await window.loadURL('http://127.0.0.1:5174');await wait(600);
  await button('Open project');await button('Local logic');
  assert.equal(await evaluate("document.querySelectorAll('.native-object-branch').length"),8);
  assert.equal(await evaluate("document.querySelectorAll('.state-branch, .base-branch, .states-branch').length"),0);
  const outline='.native-object-branch[data-object-id="selection_outline"]';
  assert.deepEqual(await evaluate(`Array.from(document.querySelectorAll('${outline} .native-object-overrides small'),e=>e.textContent)`),['Y: 38','Y: 70','Y: 102']);
  assert.equal(await evaluate("document.querySelectorAll('.native-object-overrides button').length"),3);
  await capture('logic.png');
  const previewStarts=()=>operations.filter(operation=>operation==='project.preview_reset').length;
  const starts=previewStarts();
  assert(starts>0,'The test must observe the initial emulator launch');
  await evaluate(`document.querySelector('${outline} [data-state-id="settings"]').click()`);await wait(500);
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Editing\"]').value"),'settings');
  assert.deepEqual(await evaluate("Array.from(document.querySelectorAll('.scene-object-property small'),e=>e.textContent)"),['Using scene default','Changed in this state','Using scene default']);
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Use scene default for Y\"]').title"),'Use scene default');
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Object Y\"]').value"),'70');
  assert.equal(await evaluate("document.querySelectorAll('.native-object-overrides .selected').length"),1);
  await evaluate(`document.querySelector('${outline} .hierarchy-disclosure-control').click()`);await wait(100);
  assert.equal(await evaluate(`document.querySelectorAll('${outline} .native-object-overrides').length`),0);
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Editing\"]').value"),'settings');
  await evaluate(`document.querySelector('${outline} .hierarchy-disclosure-control').click()`);await wait(100);
  assert.equal(await evaluate(`document.querySelectorAll('${outline} .native-object-overrides .selected').length`),1);
  await evaluate(`document.querySelector('${outline}').scrollIntoView({block:'nearest'})`);
  await capture('placement.png');
  assert.equal(await evaluate("document.querySelectorAll('.placement-element-box').length"),8);
  await evaluate(`document.querySelector('${outline} .placement-tree-object').click()`);await wait(200);
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Editing\"]').value"),'');
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Object Y\"]').value"),'38');
  const title='.native-object-branch[data-object-id="menu_title"]';
  await evaluate(`document.querySelector('${title} .placement-tree-object').click()`);await wait(100);
  await evaluate(`(()=>{const e=document.querySelector('[aria-label="Editing"]');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(e,'credits');e.dispatchEvent(new Event('change',{bubbles:true}));})()`);await wait(200);
  assert.equal(previewStarts(),starts,'Hierarchy and target selection must not launch the emulator');
  await evaluate(`(()=>{const e=document.querySelector('[aria-label="Object X"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,'20');e.dispatchEvent(new Event('input',{bubbles:true}));})()`);await wait(100);
  await evaluate(`document.querySelector('[aria-label="Object X"]').dispatchEvent(new FocusEvent('focusout',{bubbles:true}))`);await wait(500);
  assert.equal(await evaluate(`document.querySelector('${title} [data-state-id="credits"] small').textContent`),'X: 20');
  await evaluate(`document.querySelector('button[title="Undo"]').click()`);await wait(500);
  assert.equal(await evaluate(`document.querySelectorAll('${title} .native-object-overrides').length`),0);
  window.setSize(760,1000);await wait(300);
  await evaluate(`document.querySelector('${outline}').scrollIntoView({block:'center'})`);
  assert(await evaluate(`Array.from(document.querySelectorAll('${outline} strong')).every(e=>e.scrollWidth<=e.clientWidth)`));
  await capture('hierarchy-compact.png');
  assert.deepEqual(errors,[]);
  console.log(`Native menu opened in Studio: hierarchy, local logic and placement verified. Screenshots: ${output}`);
  child.kill();clearTimeout(watchdog);app.exit(0);
}).catch(error=>{console.error(error);child?.kill();clearTimeout(watchdog);app.exit(1)});
