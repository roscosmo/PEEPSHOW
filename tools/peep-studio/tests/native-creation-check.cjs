const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const readline = require('node:readline');
const { spawn } = require('node:child_process');
const { app, BrowserWindow, ipcMain } = require('electron');
const root = path.resolve(__dirname, '../../..');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'peep-native-'));
const projectPath = path.join(temp, 'native.peepproj');
const output = path.resolve('dist/native-creation-check');
fs.mkdirSync(output, { recursive: true });
app.setPath('userData', path.join(output, 'profile'));
app.disableHardwareAcceleration();
app.on('window-all-closed', () => {});
let child, window, latest;
let id = 0;
const pending = new Map();
const commands = [];
const serviceErrors = [];
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const watchdog = setTimeout(() => { child?.kill(); app.exit(1); }, 60000);
app.whenReady().then(async () => {
  child = spawn(process.env.PEEPSHOW_PYTHON || 'python', ['-u', 'tools/authoring/egg_tool.py', 'service'], { cwd: root, windowsHide: true });
  readline.createInterface({ input: child.stdout }).on('line', line => {
    const r = JSON.parse(line), p = pending.get(r.id); pending.delete(r.id);
    if (r.ok) p?.resolve(r.result); else { serviceErrors.push(r.error); p?.reject(new Error(JSON.stringify(r.error))); }
  });
  child.stderr.on('data', data => process.stderr.write(data));
  ipcMain.handle('native:path', () => projectPath);
  ipcMain.handle('native:service', async (_, operation, params) => {
    assert(!operation.includes('migration'), 'Creation must not migrate');
    if (operation === 'project.create') assert.equal(params.scene_schema_version, 2);
    if (operation === 'project.apply_commands') commands.push(...params.commands);
    const requestId = String(++id);
    const result = await new Promise((resolve, reject) => {
      pending.set(requestId, { resolve, reject });
      child.stdin.write(JSON.stringify({ protocol_version: 1, id: requestId, operation, params }) + '\n');
    });
    if (result.document) latest = result;
    return result;
  });
  window = new BrowserWindow({ width: 1440, height: 1000, show: false, webPreferences: {
    preload: path.join(__dirname, 'native-creation-preload.cjs'), sandbox: true, contextIsolation: true, offscreen: true, backgroundThrottling: false,
  } });
  const evaluate = code => window.webContents.executeJavaScript(code).catch(error => { throw new Error(`${code}: ${error.message}`); });
  const click = async selector => { await evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`); await wait(450); };
  const button = async label => { await evaluate(`[...document.querySelectorAll('button')].find(e => e.textContent.trim() === ${JSON.stringify(label)}).click()`); await wait(450); };
  const text = async (selector, value) => {
    await evaluate(`(() => { const e=document.querySelector(${JSON.stringify(selector)});
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});
      e.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await wait(80);
    await evaluate(`document.querySelector(${JSON.stringify(selector)}).dispatchEvent(new FocusEvent('focusout',{bubbles:true}))`);
    await wait(450);
  };
  const main = () => latest.document.scenes.find(scene => scene.scene_id === 'main');
  await window.loadURL('http://127.0.0.1:5174'); await wait(700);
  await button('New project'); await wait(600);
  assert.equal(main().schema_version, 2);
  assert.deepEqual(main().objects, []);
  assert.equal(main().states.length, 1);
  assert(!main().waiting_visuals && !main().render_models);
  assert(fs.existsSync(path.join(projectPath, 'project.json')));
  assert(await evaluate("document.querySelector('.host-preview-notice').textContent.includes('V2_OBJECTS_EMPTY')"));
  await button('Local logic');
  await click('button[title="Add state"]');
  const stateId = main().states.find(state => state.state_id !== 'start').state_id;
  assert.deepEqual(main().states.find(state => state.state_id === stateId).object_overrides, []);
  await text('[aria-label="State name"]', 'Playing');
  assert.equal(main().states.find(state => state.state_id === stateId).display_name, 'Playing');
  await button('Set as start');
  assert.equal(main().entry_state, stateId);
  await evaluate(`document.querySelector('.react-flow__node[data-id="start"]').dispatchEvent(new MouseEvent('click',{bubbles:true}))`); await wait(300);
  await click('button[title="Delete selected state"]');
  assert.equal(main().states.length, 1);
  await click('button[title="Undo"]'); assert.equal(main().states.length, 2);
  await click('button[title="Redo"]'); assert.equal(main().states.length, 1);
  const selector = `.react-flow__node[data-id="${stateId}"] .state-card-name`;
  await evaluate(`(() => {const e=document.querySelector(${JSON.stringify(selector)}),r=e.getBoundingClientRect();
    e.dispatchEvent(new MouseEvent('mousedown',{bubbles:true,view:window,button:0,buttons:1,clientX:r.x+10,clientY:r.y+10}));
    window.dispatchEvent(new MouseEvent('mousemove',{bubbles:true,view:window,buttons:1,clientX:r.x+70,clientY:r.y+50}));
    window.dispatchEvent(new MouseEvent('mouseup',{bubbles:true,view:window,button:0,clientX:r.x+70,clientY:r.y+50}));})()`);
  await wait(600);
  assert(commands.some(command => command.kind === 'editor.state_graph.set_node_position'));
  assert(!commands.some(command => command.kind.startsWith('route.') || command.kind.startsWith('scene_exit.')));
  assert(await evaluate("document.querySelector('button[title=\"Add state\"]').disabled === false"));
  window.webContents.invalidate(); await wait(300);
  fs.writeFileSync(path.join(output, 'native-states.png'), (await window.webContents.capturePage()).toPNG());
  await click('.react-flow__pane');
  await button('Add variable');
  await evaluate(`(() => {const e=[...document.querySelectorAll('.variable-add-form label')].find(e=>e.textContent.trim()==='Maximum').querySelector('input');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,'10');e.dispatchEvent(new Event('input',{bubbles:true}));})()`);await wait(100);
  await click('.variable-add-form button[type="submit"]');
  assert.equal(main().variables[0].variable_id, 'counter');
  const choose = async (selector, value) => {
    await evaluate(`(() => {const e=document.querySelector(${JSON.stringify(selector)});
      Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(e,${JSON.stringify(value)});
      e.dispatchEvent(new Event('change',{bubbles:true}));})()`); await wait(450);
  };
  await click(`.react-flow__node[data-id="${stateId}"] [data-handleid="new-physical-trigger:BUTTON_A"]`);
  await click(`.react-flow__node[data-id="${stateId}"] [data-handleid="entry-top-left:top"]`);
  await button('Create transition');
  assert.equal(main().routes.length, 1);
  const routeId = main().routes[0].route_id;
  assert.equal(main().routes[0].target_state, stateId);
  assert(commands.some(command => command.kind === 'route.create_trigger'));
  await button('Add condition');
  assert.equal(main().routes[0].guards[0].variable_ref, 'counter');
  await choose('[aria-label="Condition 1 operator"]', 'eq');
  await choose('[aria-label="Add effect"]', 'set_variable');
  assert.equal(main().routes[0].actions[0].kind, 'set_variable');
  await choose('[aria-label="Effect 1 operation"]', 'assign');
  await text('[aria-label="Effect 1 target value"]', '1');
  await choose('[aria-label="Add effect"]', 'set_variable');
  await choose('[aria-label="Effect 2 operation"]', 'add');
  await text('[aria-label="Effect 2 change amount"]', '2');
  await click('[aria-label="Move effect 2 earlier"]');
  assert.deepEqual(main().routes[0].actions.map(action=>action.operation),['add','assign']);
  assert.equal(main().routes[0].route_id,routeId);
  await click('button[title="Add state"]');
  const targetId = main().states.find(state => state.state_id !== stateId).state_id;
  await evaluate("document.querySelector('.state-transition-edge').dispatchEvent(new MouseEvent('click',{bubbles:true}))");
  await wait(300);
  await choose(`select[id="route-target-${routeId}"]`, targetId);
  assert.equal(main().routes[0].target_state, targetId);
  const beforeRebind=structuredClone(main().routes[0]);
  const reconnectPoints=await evaluate(`(() => {
    const a=document.querySelector('.react-flow__edgeupdater-source').getBoundingClientRect();
    const b=document.querySelector('.react-flow__node[data-id="${stateId}"] [data-handleid="new-physical-trigger:BUTTON_B"]').getBoundingClientRect();
    return {a:{x:Math.round(a.x+a.width/2),y:Math.round(a.y+a.height/2)},b:{x:Math.round(b.x+b.width/2),y:Math.round(b.y+b.height/2)}};
  })()`);
  window.webContents.sendInputEvent({type:'mouseMove',...reconnectPoints.a});
  window.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...reconnectPoints.a});
  for(let i=1;i<=10;i++) { window.webContents.sendInputEvent({type:'mouseMove',x:Math.round(reconnectPoints.a.x+(reconnectPoints.b.x-reconnectPoints.a.x)*i/10),y:Math.round(reconnectPoints.a.y+(reconnectPoints.b.y-reconnectPoints.a.y)*i/10)});await wait(20); }
  window.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...reconnectPoints.b});await wait(500);
  assert(commands.some(command=>command.kind==='route.rebind_trigger'&&command.route_id===routeId&&command.logical_source==='BUTTON_B'));
  assert.deepEqual({...main().routes[0],action_ref:beforeRebind.action_ref},beforeRebind);
  const request = (operation, params) => new Promise((resolve, reject) => {
    const requestId = String(++id); pending.set(requestId, {resolve, reject});
    child.stdin.write(JSON.stringify({protocol_version:1,id:requestId,operation,params})+'\n');
  });
  let snapshot = await request('project.preview_reset', {project_revision:latest.project_revision,scene_id:'main',state_id:stateId});
  await text('[aria-label="Condition 1 value"]','1');
  snapshot = await request('project.preview_reset', {project_revision:latest.project_revision,scene_id:'main',state_id:stateId});
  snapshot = await request('project.preview_input', {project_revision:latest.project_revision,
    preview_revision:snapshot.preview_revision,logical_source:'BUTTON_B'});
  assert.equal(snapshot.scene.state_id,stateId,'Edited guard must reject the input');
  assert.equal(snapshot.variables.counter,0);
  await text('[aria-label="Condition 1 value"]','0');
  snapshot = await request('project.preview_reset', {project_revision:latest.project_revision,scene_id:'main',state_id:stateId});
  snapshot = await request('project.preview_input', {project_revision:latest.project_revision,
    preview_revision:snapshot.preview_revision,logical_source:'BUTTON_B'});
  assert.equal(snapshot.variables.counter, 1, 'The authored guarded button route must execute in the host');
  assert.equal(snapshot.scene.state_id, targetId);
  await click('[aria-label="Move effect 1 later"]');
  snapshot = await request('project.preview_reset', {project_revision:latest.project_revision,scene_id:'main',state_id:stateId});
  snapshot = await request('project.preview_input', {project_revision:latest.project_revision,
    preview_revision:snapshot.preview_revision,logical_source:'BUTTON_B'});
  assert.equal(snapshot.variables.counter,3,'Assign then add must differ from add then assign');
  assert.equal(main().routes[0].route_id,routeId);
  const editedRoute=structuredClone(main().routes[0]);
  await click('button[title="Undo"]');
  assert.deepEqual(main().routes[0].actions.map(action=>action.operation),['add','assign']);
  await click('button[title="Redo"]');assert.deepEqual(main().routes[0],editedRoute);
  await button('Save');await button('Open project');
  assert.deepEqual(main().routes[0],editedRoute);
  await button('Local logic');
  await evaluate("document.querySelector('.state-transition-edge').dispatchEvent(new MouseEvent('click',{bubbles:true}))");await wait(300);
  console.log('Existing route edit: stable identity, guards reject/accept, ordered calculations, destination, undo/redo and save/reopen passed');
  assert(commands.some(command => command.kind === 'object_actions.set' && command.owner_id === routeId));
  assert(!commands.some(command => command.kind.startsWith('route.action.') || command.kind === 'route.set_action'));
  window.webContents.invalidate(); await wait(200);
  fs.writeFileSync(path.join(output, 'native-local-graph.png'), (await window.webContents.capturePage()).toPNG());
  await click('button[title="Delete transition"]');
  assert.equal(main().routes.length, 0);
  await click('button[title="Undo"]'); assert.equal(main().routes.length, 1);
  await click('button[title="Redo"]'); assert.equal(main().routes.length, 0);
  assert(!commands.some(command => command.kind.startsWith('scene_exit.')));
  await button('Scene flow');
  await click('button[title="New scene"]');
  await text('[aria-label="New scene name"]', 'Garden');
  await click('button[title="Create scene"]');
  assert.equal(latest.document.scenes.length, 2);
  assert(latest.document.scenes.every(scene => scene.schema_version === 2));
  assert.equal(commands.find(command => command.kind === 'scene.add').scene_schema_version, 2);
  const gardenId = latest.document.scenes.find(scene => scene.scene_id !== 'main').scene_id;
  await click('.project-root-row');
  await evaluate(`(() => { const e=document.querySelector('[aria-label="Project entry scene"]');
    Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(e,${JSON.stringify(gardenId)});
    e.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await wait(450);
  assert.equal(latest.summary.entry_scene, gardenId);
  assert(commands.some(command => command.kind === 'project.set_entry_scene' && command.scene_id === gardenId));
  await button('Save');
  const saved = JSON.stringify(latest.document.scenes);
  const reload = await new Promise((resolve,reject) => { const requestId=String(++id); pending.set(requestId,{resolve,reject});
    child.stdin.write(JSON.stringify({protocol_version:1,id:requestId,operation:'project.load',params:{path:projectPath}})+'\n'); });
  assert.equal(JSON.stringify(reload.document.scenes), saved);
  assert.deepEqual(serviceErrors, [], 'Native workflow must not generate service errors');
  console.log('Native creation, state lifecycle, local graph/guard/actions, scene addition and save/reload passed');
}).catch(error => { console.error(error); process.exitCode = 1; }).finally(() => {
  clearTimeout(watchdog); child?.kill(); window?.destroy(); fs.rmSync(temp,{recursive:true,force:true}); app.exit(process.exitCode || 0);
});
